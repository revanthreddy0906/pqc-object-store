def robustness(runs_x: list[dict], runs_a: list[dict], tx: dict, ta: dict, families: dict,
               results: Path, m: Macros) -> None:
    """Order and time effects: the mode coefficient of an OLS on log throughput with block
    (repetition) fixed effects and run-order covariates, against the plain paired ratio."""
    records = []
    for plat, runs, fam in (("x86", runs_x, families["x86"][("P1", "B2")]),
                            ("arm", runs_a, families["arm"][("P1", "B2")])):
        for row in fam:
            mine = [r for r in runs if r["experiment"] == row["experiment"]
                    and r["operation"] == row["operation"] and r["size"] == row["size"]
                    and r["concurrency"] == row["concurrency"] and r["loop"] == "closed"
                    and r["mode"] in ("P1", "B2")]
            reps = sorted({r["repetition"] for r in mine})
            first = min(r["started_unix"] for r in mine)
            design, y = [], []
            for r in mine:
                design.append([1.0 if r["mode"] == "P1" else 0.0,
                               (r["started_unix"] - first) / 3600.0,
                               float(r["position_in_block"]),
                               1.0 if r["previous_operation"] == "put" else 0.0]
                              + [1.0 if r["repetition"] == rep else 0.0 for rep in reps])
                y.append(math.log(r["ops_per_s"]))
            beta, *_ = np.linalg.lstsq(np.asarray(design), np.asarray(y), rcond=None)
            cv = {mode: statistics.stdev(r["ops_per_s"] for r in mine if r["mode"] == mode)
                  / statistics.fmean(r["ops_per_s"] for r in mine if r["mode"] == mode)
                  for mode in ("P1", "B2")}
            records.append({"platform": plat, "operation": row["operation"], "size": row["size"],
                            "concurrency": row["concurrency"], "paired_ratio": row["ratio"],
                            "adjusted_ratio": math.exp(beta[0]),
                            "shift": abs(math.exp(beta[0]) / row["ratio"] - 1),
                            "cv_p1": cv["P1"], "cv_b2": cv["B2"]})
    fa.write_csv(results / "robustness.csv", records)
    m.add("RevOrderShiftMax", num(100 * max(r["shift"] for r in records), 1))
    quiet = [r for r in records if not (r["operation"] == "put" and r["size"] == 65536)]
    noisy = [r for r in records if r["operation"] == "put" and r["size"] == 65536]
    m.add("RevOrderShiftMaxQuiet", num(100 * max(r["shift"] for r in quiet), 1))
    m.add("RevCvQuietMax", num(100 * max(max(r["cv_p1"], r["cv_b2"]) for r in quiet), 1))
    m.add("RevCvNoisyLo", num(100 * min(min(r["cv_p1"], r["cv_b2"]) for r in noisy), 0))
    m.add("RevCvNoisyHi", num(100 * max(max(r["cv_p1"], r["cv_b2"]) for r in noisy), 0))
    # Achieved power of one TOST (alpha = 0.05, true ratio 1) at the observed paired SDs, and
    # the repetitions that 80% power would need in the noisiest primary cell.
    by = {(r["operation"], r["size"], r["concurrency"]): r for r in families["x86"][("P1", "B2")]}
    noisy_sd = by[("put", 65536, 128)]["sd_log"]
    m.add("RevPowerNoisy", num(100 * stats.tost_power(noisy_sd, 10, draws=4000), 0))
    m.add("RevPowerKnee", num(100 * stats.tost_power(by[("put", 65536, 32)]["sd_log"], 20,
                                                     draws=4000), 0))
    m.add("RevPowerQuiet", num(100 * stats.tost_power(by[("put", MIB, 32)]["sd_log"], 10,
                                                      draws=4000), 0))
    m.add("RevPowerNoisyNeeded", next(n for n in (20, 30, 40, 50, 60, 80, 100, 150, 200)
                                      if stats.tost_power(noisy_sd, n, draws=3000) >= 0.8))
    for name, runs in (("Rev", runs_x), ("Arm", runs_a)):
        m.add(f"{name}Stalls", sum(r["stall"] for r in runs))
        m.add(f"{name}StallsSmallPut", sum(r["stall"] for r in runs
                                           if r["operation"] == "put" and r["size"] <= 65536))
    # Throughput of the noisy cells against the server's CPU use (the stall signature).
    cell = [r for r in runs_x if r["experiment"] == "final-e" and r["operation"] == "put"
            and r["size"] == 65536 and r["concurrency"] == 128]
    m.add("RevNoisyCpuCorr", f"{np.corrcoef([r['ops_per_s'] for r in cell], [r['server_cores'] for r in cell])[0, 1]:.2f}")
    m.add("RevNoisyRuns", len(cell))


