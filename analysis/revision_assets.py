def baseline(root: Path, stamp_prefix: str) -> tuple[float, float, float, float]:
    iperf = json.loads(max(root.glob(f"iperf3-{stamp_prefix}*.json")).read_text())
    gbit = iperf["end"]["sum_received"]["bits_per_second"] / 1e9
    ping = max(root.glob(f"ping-{stamp_prefix}*.txt")).read_text()
    rtt = float(re.search(r"= [\d.]+/([\d.]+)/", ping).group(1))
    fio = json.loads(max(root.glob(f"fio-{stamp_prefix}*.json")).read_text())["jobs"]
    read = max(j["read"]["bw_bytes"] for j in fio) / MIB
    write = max(j["write"]["bw_bytes"] for j in fio) / MIB
    return gbit, rtt, read, write


def totals(runs_x: list[dict], runs_a: list[dict], baselines: Path, m: Macros) -> None:
    for name, runs, stamp in (("Rev", runs_x, "20261011"), ("Arm", runs_a, "20261012")):
        m.add(f"{name}Runs", num(len(runs)))
        m.add(f"{name}Requests", f"{sum(r['requests'] for r in runs) / 1e6:.1f}")
        m.add(f"{name}Failures", num(sum(r["failures"] for r in runs)))
        m.add(f"{name}Invalid", sum(not r["valid"] for r in runs))
        m.add(f"{name}SettleMedian", f"{statistics.median(r['settle_s'] for r in runs):.1f}")
        gbit, rtt, read, write = baseline(baselines, stamp)
        m.add(f"{name}LinkGbit", f"{gbit:.1f}")
        m.add(f"{name}Rtt", f"{rtt:.2f}")
        m.add(f"{name}DiskRead", num(read, -1))
        m.add(f"{name}DiskWrite", num(write, -1))
    import yaml
    config_env = dict(line.split("#")[0].strip().split("=", 1)
                      for line in Path("infra/aws/config.env").read_text().splitlines()
                      if "=" in line.split("#")[0])
    m.add("RevRegion", config_env["REGION"])
    for name, exp in (("Rev", "final-e"), ("Arm", "final-i")):
        manifest = yaml.safe_load(max(Path("experiments", exp).glob("*/run-manifest.yaml")).read_text())
        env = manifest["environment"]
        cpu = env["cpu_model"].replace("(R)", "").strip()
        # /proc/cpuinfo has no model name on ARM; c7g instances are AWS Graviton3 (AWS documentation).
        m.add(f"{name}ClientCPU", "AWS Graviton3" if cpu == "aarch64" else cpu)
        m.add(f"{name}Kernel", env["platform"].split("-")[1])
        m.add(f"{name}Commit", str(manifest.get("git_commit", env.get("git_commit", "")))[:7])
    both = runs_x + runs_a
    m.add("RevAllRuns", num(len(both)))
    m.add("RevAllRequests", f"{sum(r['requests'] for r in both) / 1e6:.1f}")
    for exp, tag in (("final-e", "E"), ("final-ek", "EK"), ("final-f", "F"), ("final-g", "G"),
                     ("final-h", "H"), ("final-i", "I"), ("final-ik", "IK"), ("final-i1", "IOne")):
        m.add(f"RevBatch{tag}Runs", sum(r["experiment"] == exp for r in both))


