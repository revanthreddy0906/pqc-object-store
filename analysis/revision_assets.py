def tex_table(path: Path, header: list[str], rows: list[list[str]], align: str,
              group: str | None = None) -> None:
    """A booktabs tabular; `group` is an optional first header line of \\multicolumn cells."""
    body = " \\\\\n".join(" & ".join(r) for r in rows)
    top = f"{group} \\\\\n" if group else ""
    path.write_text(f"{HEADER}\\begin{{tabular}}{{{align}}}\n\\toprule\n{top}"
                    f"{' & '.join(header)} \\\\\n\\midrule\n{body} \\\\\n\\bottomrule\n"
                    "\\end{tabular}\n", encoding="utf-8")


def load(path: Path) -> tuple[list[dict], dict]:
    runs = [r for r in fa.load_runs(path) if r["experiment"] != "final-p"]
    fa.flag_stalls(runs)
    return runs, fa.cells(runs)


def pval(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def ci(lo: float, hi: float, digits: int = 3) -> str:
    return f"{lo:.{digits}f}--{hi:.{digits}f}"


def cell_label(row: dict) -> str:
    return f"{size_label(row['size'])} {row['operation'].upper()}, {row['concurrency']}"


VERDICT = {"equivalent": "Eq.", "inconclusive": "Inc.", "different": "Non-eq."}


# ---------------------------------------------------------------- equivalence family

def tost_tables(tx: dict, ta: dict, out: Path, results: Path, m: Macros) -> dict:
    families = {
        "x86": {pair: fa.tost_family(tx, X86, *pair) for pair in
                (("P1", "B2"), ("P3", "B2"), ("P3", "P1"), ("P2", "P1"), ("R1", "P1"))},
        "arm": {pair: fa.tost_family(ta, ARM, *pair) for pair in
                (("P1", "B2"), ("P3", "B2"), ("P3", "P1"))},
    }
    flat = [{"platform": plat, **row} for plat, fam in families.items()
            for rows in fam.values() for row in rows]
    fa.write_csv(results / "tost.csv", flat)

    px, pa = families["x86"][("P1", "B2")], families["arm"][("P1", "B2")]
    rows = []
    for x, a in zip(px, pa):
        rows.append([cell_label(x), str(x["n"]), f"{x['ratio']:.3f}",
                     ci(x["ci90_lo"], x["ci90_hi"]), ci(x["ci95_lo"], x["ci95_hi"]),
                     pval(x["p_holm"]), VERDICT[x["verdict_holm"]],
                     "yes" if x["equivalent_at_2pct"] else "no",
                     f"{a['ratio']:.3f}", ci(a["ci90_lo"], a["ci90_hi"]), pval(a["p_holm"]),
                     VERDICT[a["verdict_holm"]]])
    tex_table(out / "tab-tost.tex",
              ["Cell (size, op., workers)", "$n$", "Ratio", "90\\% CI", "95\\% CI",
               "$p_{\\text{Holm}}$", "Verdict", "$\\pm$2\\%", "Ratio", "90\\% CI",
               "$p_{\\text{Holm}}$", "Verdict"], rows, "lrcccclc|cccl",
              " & \\multicolumn{7}{c|}{x86 client (batches E, EK)} & "
              "\\multicolumn{4}{c}{ARM client (batches I, IK)}")

    # Exploratory comparisons: unadjusted p-values, verdict at alpha = 0.05 per test.
    rows = []
    for i, x in enumerate(px):
        line = [cell_label(x)]
        for plat, pair in (("x86", ("P3", "B2")), ("x86", ("P3", "P1")), ("x86", ("P2", "P1")),
                           ("arm", ("P3", "B2")), ("arm", ("P3", "P1"))):
            r = families[plat][pair][i]
            line.append(f"{r['ratio']:.3f} ({VERDICT[r['verdict']]})")
        rows.append(line)
    tex_table(out / "tab-secondary.tex",
              ["Cell", "P3/B2", "P3/P1", "P2/P1", "P3/B2", "P3/P1"], rows, "lccc|cc",
              " & \\multicolumn{3}{c|}{x86 client} & \\multicolumn{2}{c}{ARM client}")

    for plat, name in (("x86", "Rev"), ("arm", "Arm")):
        fam = families[plat][("P1", "B2")]
        for verdict, tag in (("equivalent", "Eq"), ("inconclusive", "Inc"), ("different", "Diff")):
            m.add(f"{name}Primary{tag}", sum(r["verdict_holm"] == verdict for r in fam))
        m.add(f"{name}PrimaryEqTwoPct", sum(r["equivalent_at_2pct"] for r in fam))
        m.add(f"{name}PrimaryEqTenPct", sum(r["equivalent_at_10pct"] for r in fam))
        m.add(f"{name}PrimaryNoStallSame",
              sum(r["verdict"] == r["verdict_nostall"] for r in fam))
        m.add(f"{name}PrimaryStalledPairs", sum(r["stalled_pairs"] for r in fam))
        by = {(r["operation"], r["size"], r["concurrency"]): r for r in fam}
        hot = by[("get", 65536, 500)]
        m.add(f"{name}HotRatio", f"{hot['ratio']:.3f}")
        m.add(f"{name}HotDeficit", num((1 - hot["ratio"]) * 100, 1))
        m.add(f"{name}HotCI", ci(hot["ci90_lo"], hot["ci90_hi"]))
        noisy = by[("put", 65536, 128)]
        m.add(f"{name}NoisyRatio", f"{noisy['ratio']:.3f}")
        m.add(f"{name}NoisyCI", ci(noisy["ci90_lo"], noisy["ci90_hi"], 2))
        m.add(f"{name}NoisySd", num(noisy["sd_log"] * 100, 0))
        knee = by[("put", 65536, 32)]
        m.add(f"{name}KneeRatio", f"{knee['ratio']:.3f}")
        m.add(f"{name}KneeCI", ci(knee["ci90_lo"], knee["ci90_hi"]))
        m.add(f"{name}KneeP", pval(knee["p_tost"]))
        m.add(f"{name}KneePHolm", pval(knee["p_holm"]))
        m.add(f"{name}KneeSd", num(knee["sd_log"] * 100, 0))
        large = [r for r in fam if r["size"] >= MIB]
        m.add(f"{name}LargeRatioLo", f"{min(r['ratio'] for r in large):.3f}")
        m.add(f"{name}LargeRatioHi", f"{max(r['ratio'] for r in large):.3f}")
        xw = {(r["operation"], r["size"], r["concurrency"]): r
              for r in families[plat][("P3", "B2")]}
        m.add(f"{name}XwingHotDeficit", num((1 - xw[("get", 65536, 500)]["ratio"]) * 100, 1))
        m.add(f"{name}XwingMidDeficit", num((1 - xw[("get", 65536, 128)]["ratio"]) * 100, 1))
        m.add(f"{name}XwingEq", sum(r["verdict"] == "equivalent"
                                    for r in families[plat][("P3", "B2")]))
        m.add(f"{name}XwingNonEq", sum(r["verdict"] == "different"
                                       for r in families[plat][("P3", "B2")]))
        xp = {(r["operation"], r["size"], r["concurrency"]): r
              for r in families[plat][("P3", "P1")]}
        m.add(f"{name}XwingVsMlkemHotDeficit",
              num((1 - xp[("get", 65536, 500)]["ratio"]) * 100, 1))
    pp = families["x86"][("P2", "P1")]
    m.add("RevStudyHybridEq", sum(r["verdict"] == "equivalent" for r in pp))
    m.add("RevStudyHybridLo", f"{min(r['ratio'] for r in pp):.3f}")
    rsa = families["x86"][("R1", "P1")]
    m.add("RevRsaGetLo", f"{min(r['ratio'] for r in rsa):.2f}")
    m.add("RevRsaGetHi", f"{max(r['ratio'] for r in rsa):.2f}")
    return families


def fig_tost(tx: dict, ta: dict, families: dict, out: Path) -> None:
    """Forest plot of the primary family: every paired run ratio, the mean and its 90% CI."""
    fig, ax = plt.subplots(figsize=(3.5, 2.9))
    px = families["x86"][("P1", "B2")]
    labels = []
    for i, x in enumerate(px):
        y0 = len(px) - 1 - i
        labels.append(cell_label(x).replace("\\,", " "))
        for table, exps, fam, dy, colour, marker, name in (
                (tx, X86, px, 0.17, COLOR["P1"], "o", "x86 client"),
                (ta, ARM, families["arm"][("P1", "B2")], -0.17, COLOR["R1"], "s", "ARM client")):
            row = fam[i]
            key = (row["experiment"], row["operation"], row["size"], "closed",
                   row["concurrency"], 0.0)
            logs = fa.log_ratios(table[(*key, "P1", 0, False)]["runs"],
                                 table[(*key, "B2", 0, False)]["runs"], "ops_per_s")
            rng = np.random.default_rng(i)
            ax.plot(np.exp(logs), y0 + dy + rng.uniform(-0.09, 0.09, len(logs)), linestyle="none",
                    marker=".", markersize=2.5, color=colour, alpha=0.35)
            ax.errorbar([row["ratio"]], [y0 + dy],
                        xerr=[[row["ratio"] - row["ci90_lo"]], [row["ci90_hi"] - row["ratio"]]],
                        color=colour, marker=marker, markersize=3, capsize=2, elinewidth=1.0,
                        label=name if i == 0 else None)
    ax.axvspan(0.95, 1.05, color="#e9e6f5", zorder=0)
    ax.axvline(1.0, color=INK2, linewidth=0.6)
    ax.set_yticks(range(len(px)))
    ax.set_yticklabels(labels[::-1], fontsize=6.5)
    ax.set_xlim(0.78, 1.32)
    ax.set_xlabel("throughput ratio ML-KEM-768 / X25519 (paired runs)")
    ax.grid(axis="y", visible=False)
    ax.legend(loc="lower right", fontsize=6)
    fig.tight_layout()
    fig.savefig(out / "fig-tost.pdf")
    plt.close(fig)


