def key_establishment(tx: dict, ta: dict, out: Path, m: Macros) -> None:
    rows = []
    names = {"B2": "Ecdh", "P1": "MLKEM", "P2": "StudyHybrid", "P3": "Xwing"}
    for mode in ("B2", "P1", "P2", "P3"):
        line = [mpa.LABEL.get(mode, "P3 X-Wing")]
        for table, exp in ((tx, "final-f"), (ta, "final-i1")):
            for op in ("put", "get"):
                c = table.get((exp, op, 65536, "closed", 1, 0.0, mode, 0, False))
                line.append("--" if c is None else f"{c['ke_mean_ms']:.3f}")
                if c is not None:
                    plat = "Rev" if exp == "final-f" else "Arm"
                    m.add(f"{plat}Ke{names[mode]}{op.capitalize()}", f"{c['ke_mean_ms']:.3f}")
                    m.add(f"{plat}KeShare{names[mode]}{op.capitalize()}",
                          num(c["ke_share"] * 100, 1))
        rows.append(line)
    tex_table(out / "tab-ke.tex", ["Mode", "PUT", "GET", "PUT", "GET"], rows, "lcc|cc",
              " & \\multicolumn{2}{c|}{x86 (ms)} & \\multicolumn{2}{c}{ARM (ms)}")
    f = lambda op, mode: tx[("final-f", op, 65536, "closed", 1, 0.0, mode, 0, False)]["ke_mean_ms"]
    m.add("RevXwingOverMlkemPut", f"{f('put', 'P3') / f('put', 'P1'):.1f}")
    m.add("RevXwingOverMlkemGet", f"{f('get', 'P3') / f('get', 'P1'):.1f}")
    m.add("RevKeSumGet", f"{f('get', 'P1') + f('get', 'B2'):.3f}")
    mid = tx[("final-f", "put", MIB, "closed", 1, 0.0, "P3", 0, False)]
    m.add("RevKeShareXwingMidPut", num(mid["ke_share"] * 100, 1))
    big = tx[("final-f", "put", 128 * MIB, "closed", 1, 0.0, "P3", 0, False)]
    m.add("RevKeShareXwingLarge", num(big["ke_share"] * 100, 2))


# ---------------------------------------------------------------- hybrid matrix

def hybrid(tx: dict, out: Path, results: Path, m: Macros) -> None:
    workloads = [("final-f", s, c) for s in (1024,) for c in (1, 128)]
    workloads += [("final-f", 65536, 1), ("final-e", 65536, 128)]
    workloads += [("final-f", s, c) for s in (MIB, 16 * MIB) for c in (1, 128)]
    workloads += [("final-f", 128 * MIB, 1)]
    rows, records = [], []
    for exp, size, conc in workloads:
        for op in ("put", "get"):
            base = tx.get((exp, op, size, "closed", conc, 0.0, "B2", 0, False))
            if base is None:
                continue
            line = [f"{size_label(size)} {op.upper()}", str(conc), num(base["ops_per_s"], 0),
                    num(base["mib_per_s"], 0 if base["mib_per_s"] >= 100 else 1)]
            for metric in ("ops_per_s", "p99_ms", "cpu_ms_per_req"):
                for mode in ("P1", "P2", "P3"):
                    other = tx[(exp, op, size, "closed", conc, 0.0, mode, 0, False)]
                    r, lo, hi, n = fa.paired(other["runs"], base["runs"], metric)
                    mark = "$^{*}$" if not (lo <= 1 <= hi) else ""
                    line.append(f"{r:.2f}{mark}")
                    records.append({"experiment": exp, "operation": op, "size": size,
                                    "concurrency": conc, "mode": mode, "metric": metric,
                                    "ratio": r, "ci95_lo": lo, "ci95_hi": hi, "n": n,
                                    "p50_ms": other["p50_ms"], "p99_ms": other["p99_ms"],
                                    "rss_peak_mib": other["client_rss_peak_mib"]})
            rows.append(line)
    fa.write_csv(results / "hybrid.csv", records)
    tex_table(out / "tab-hybrid.tex",
              ["Workload", "$c$", "req/s", "MiB/s", "P1", "P2", "P3", "P1", "P2", "P3",
               "P1", "P2", "P3"], rows, "lrrr|ccc|ccc|ccc",
              " & & \\multicolumn{2}{c|}{X25519 (B2)} & \\multicolumn{3}{c|}{Throughput ratio} & "
              "\\multicolumn{3}{c|}{p99 latency ratio} & \\multicolumn{3}{c}{Client CPU/request ratio}")
    thr = [r for r in records if r["metric"] == "ops_per_s"]
    for mode, name in (("P2", "StudyHybrid"), ("P3", "Xwing")):
        mine = [r for r in thr if r["mode"] == mode]
        m.add(f"RevMatrix{name}Lo", f"{min(r['ratio'] for r in mine):.2f}")
        m.add(f"RevMatrix{name}Hi", f"{max(r['ratio'] for r in mine):.2f}")
        m.add(f"RevMatrix{name}Within",
              sum(0.95 <= r["ratio"] <= 1.05 for r in mine))
    m.add("RevMatrixCells", len([r for r in thr if r["mode"] == "P3"]))
    for mode, name in (("P2", "StudyHybrid"), ("P3", "Xwing")):
        r = next(r for r in thr if r["mode"] == mode and r["operation"] == "put"
                 and r["size"] == MIB and r["concurrency"] == 1)
        m.add(f"RevMidPut{name}Deficit", num((1 - r["ratio"]) * 100, 0))
    cpu = [r for r in records if r["metric"] == "cpu_ms_per_req" and r["mode"] == "P3"]
    m.add("RevMatrixXwingCpuHi", num((max(r["ratio"] for r in cpu) - 1) * 100, 0))
    # Memory: largest difference in client peak RSS between a hybrid mode and X25519.
    rss, rel = [], []
    for key, c in tx.items():
        exp, op, size, loop, conc, rate, mode = key[:7]
        if exp in ("final-e", "final-f") and mode in ("P1", "P2", "P3") and loop == "closed":
            base = tx.get((exp, op, size, loop, conc, rate, "B2", 0, False))
            if base:
                rss.append(abs(c["client_rss_peak_mib"] - base["client_rss_peak_mib"]))
                rel.append(rss[-1] / base["client_rss_peak_mib"])
    m.add("RevHybridRssDiffMedian", num(statistics.median(rss), 0))
    m.add("RevHybridRssDiffMedianPct", num(100 * statistics.median(rel), 1))
    m.add("RevHybridRssDiffMaxPct", num(100 * max(rel), 0))


# ---------------------------------------------------------------- metadata scaling

def metadata(meta_csv: Path, out: Path, m: Macros) -> None:
    sizes = {r["mode"]: int(r["metadata_bytes"]) for r in csv.DictReader(meta_csv.open())}
    names = {"B2": "Ecdh", "P1": "MLKEM", "P2": "StudyHybrid", "P3": "Xwing"}
    rows = []
    for mode in ("B2", "P1", "P2", "P3"):
        extra = sizes[mode] - sizes["B2"]
        m.add(f"RevMeta{names[mode]}", num(sizes[mode]))
        line = [mpa.LABEL.get(mode, "P3 X-Wing"), num(sizes[mode]), num(extra) if extra else "--"]
        for count in (10**6, 10**8, 10**9):
            total = extra * count
            line.append("--" if not extra else f"{num(total / 1e9, 1)}\\,GB" if total < 1e12
                        else f"{total / 1e12:.2f}\\,TB")
        for size in (1024, 65536, MIB):
            line.append("--" if not extra else f"{100 * extra / size:.2f}\\%"
                        if extra / size < 0.1 else f"{100 * extra / size:.0f}\\%")
        rows.append(line)
    tex_table(out / "tab-meta.tex",
              ["Mode", "Manifest (B)", "Extra (B)", "$10^6$", "$10^8$", "$10^9$",
               "1\\,KiB", "64\\,KiB", "1\\,MiB"], rows, "lrr|rrr|rrr",
              " & & & \\multicolumn{3}{c|}{Extra storage at object count} & "
              "\\multicolumn{3}{c}{Share of payload}")
    extra = sizes["P1"] - sizes["B2"]
    m.add("RevMetaExtraMLKEM", num(extra))
    m.add("RevMetaExtraXwing", num(sizes["P3"] - sizes["B2"]))
    m.add("RevMetaXwingOverMLKEM", num(sizes["P3"] - sizes["P1"]))
    m.add("RevMetaBillionTB", f"{extra * 1e9 / 1e12:.2f}")
    m.add("RevMetaBillionTiB", f"{extra * 1e9 / 2**40:.2f}")
    m.add("RevMetaMillionGB", f"{extra * 1e6 / 1e9:.2f}")
    m.add("RevMetaMillionGiB", f"{extra * 1e6 / 2**30:.2f}")


# ---------------------------------------------------------------- sessions

def sessions(runs: list[dict], out: Path, results: Path, m: Macros) -> None:
    g = [r for r in runs if r["experiment"] == "final-g"]
    groups = defaultdict(list)
    for r in g:
        groups[(r["operation"], r["loop"], r["mode"], r["session_bmax"],
                r["session_tmax_s"])].append(r)

    def stat(op, loop, bmax, tmax):
        mine, ref = groups[(op, loop, "N1", bmax, float(tmax))], groups[(op, loop, "P1", 0, 0.0)]
        latency = "p99_ms" if loop == "closed" else "sojourn_p99_ms"
        row = {"operation": op, "loop": loop, "bmax": bmax, "tmax_s": tmax,
               "kem_per_object": statistics.fmean(r["kem_per_object_observed"] for r in mine),
               "objects_median": statistics.median(r["root_objects_median"] for r in mine),
               "objects_p95": statistics.median(r["root_objects_p95"] for r in mine),
               "objects_max": max(r["root_objects_max"] for r in mine),
               "kib_max": max(r["root_mib_max"] for r in mine) * 1024}
        for metric, name in (("ops_per_s", "throughput"), (latency, "p99"),
                             ("cpu_ms_per_req", "cpu")):
            row[name], row[f"{name}_lo"], row[f"{name}_hi"], _ = fa.paired(mine, ref, metric)
        return row

    records, rows = [], []
    for loop in ("closed", "open"):
        for bmax in (1, 10, 100, 1000):
            for tmax in (1, 10, 60):
                row = stat("put", loop, bmax, tmax)
                records.append(row)
                if loop == "open" and bmax < 100:
                    continue
                sig = lambda k: "$^{*}$" if not (row[f"{k}_lo"] <= 1 <= row[f"{k}_hi"]) else ""
                rows.append([("closed, 32 workers" if loop == "closed" else "open, 1{,}500/s"),
                             num(bmax), str(tmax), f"{row['kem_per_object']:.4f}",
                             f"{row['cpu']:.3f}{sig('cpu')}",
                             f"{row['throughput']:.3f}{sig('throughput')}",
                             f"{row['p99']:.2f}{sig('p99')}",
                             f"{row['objects_median']:.0f}/{row['objects_p95']:.0f}/"
                             f"{row['objects_max']:.0f}", num(row["kib_max"], 0)])
    for op in ("get",):
        for bmax in (1, 10, 100, 1000):
            mine = groups[(op, "closed", "N1", bmax, 60.0)]
            ref = groups[(op, "closed", "P1", 0, 0.0)]
            r, lo, hi, _ = fa.paired(mine, ref, "ops_per_s")
            records.append({"operation": op, "loop": "closed", "bmax": bmax, "tmax_s": 60,
                            "throughput": r, "throughput_lo": lo, "throughput_hi": hi,
                            "ke_ms": statistics.fmean(x["ke_mean_ms"] for x in mine)})
    fa.write_csv(results / "sessions.csv", records)
    tex_table(out / "tab-session.tex",
              ["Load", "$B_{\\max}$", "$T_{\\max}$ (s)", "KEM/object", "CPU", "Throughput",
               "p99", "Objects/root (med/p95/max)", "Max KiB/root"], rows, "lrrcccccr")

    by = {(r["loop"], r["bmax"], r["tmax_s"]): r for r in records if r["operation"] == "put"}
    closed = [r for r in records if r["operation"] == "put" and r["loop"] == "closed"
              and r["bmax"] >= 10]
    m.add("RevSessCpuSavingLo", num((1 - max(r["cpu"] for r in closed)) * 100, 1))
    m.add("RevSessCpuSavingHi", num((1 - min(r["cpu"] for r in closed)) * 100, 1))
    m.add("RevSessThroughputLo", f"{min(r['throughput'] for r in closed):.3f}")
    m.add("RevSessThroughputHi", f"{max(r['throughput'] for r in closed):.3f}")
    m.add("RevSessThroughputSig", sum(not (r["throughput_lo"] <= 1 <= r["throughput_hi"])
                                      for r in closed))
    m.add("RevSessConfigs", len(closed))
    one = by[("closed", 1, 60)]
    m.add("RevSessBoneCpu", num((one["cpu"] - 1) * 100, 1))
    short = by[("closed", 1000, 1)]
    m.add("RevSessShortKem", f"{short['kem_per_object']:.4f}")
    m.add("RevSessShortObjects", num(short["objects_median"]))
    m.add("RevSessShortObjectsMax", num(short["objects_max"]))
    light = by[("open", 1000, 1)]
    m.add("RevSessLightObjects", num(light["objects_median"]))
    m.add("RevSessLightKem", f"{light['kem_per_object']:.4f}")
    m.add("RevSessLightHundredObjects", num(by[("open", 100, 1)]["objects_median"]))
    full = by[("closed", 1000, 60)]
    m.add("RevSessFullKem", f"{full['kem_per_object']:.4f}")
