def profiles(root: Path, out: Path, results: Path, m: Macros) -> None:
    strace_dir = next(d for d in sorted(root.iterdir()) if not d.name.startswith("perf-"))
    perf_dir = next(d for d in sorted(root.iterdir()) if d.name.startswith("perf-"))
    calls, seconds = defaultdict(int), defaultdict(float)
    for path in sorted(strace_dir.glob("*-strace.txt")):
        for line in path.read_text().splitlines():
            parts = line.split()
            if len(parts) >= 5 and parts[0].replace(".", "").isdigit() and parts[-1] != "total":
                seconds[parts[-1]] += float(parts[1])
                calls[parts[-1]] += int(parts[3])
    total_s, total_calls = sum(seconds.values()), sum(calls.values())
    namespace = ("mkdirat", "openat", "renameat", "unlinkat", "faccessat", "lsetxattr", "close",
                 "newfstatat")
    sync_calls = ("fsync", "fdatasync", "sync_file_range", "syncfs", "msync")
    sync = sum(calls[c] for c in sync_calls)
    sync_seconds = sum(seconds[c] for c in sync_calls)
    groups = {"Lock waiting (futex)": ("futex",), "Namespace and metadata": namespace,
              "Data write": ("write", "pwrite64", "writev"),
              "Read (network and files)": ("read", "pread64", "readv"),
              "Durability (fdatasync)": sync_calls}
    rows, records = [], []
    for name, members in groups.items():
        share_t = sum(seconds[c] for c in members) / total_s
        share_c = sum(calls[c] for c in members) / total_calls
        rows.append([name, f"{100 * share_t:.1f}\\%", f"{100 * share_c:.1f}\\%"])
        records.append({"group": name, "time_share": share_t, "call_share": share_c,
                        "calls": sum(calls[c] for c in members)})
    fa.write_csv(results / "profile_syscalls.csv", records)
    tex_table(out / "tab-profile.tex", ["System-call group", "Traced time", "Calls"], rows, "lrr")
    m.add("RevProfFutexTime", num(100 * seconds["futex"] / total_s, 0))
    m.add("RevProfNamespaceTime", num(100 * sum(seconds[c] for c in namespace) / total_s, 0))
    m.add("RevProfNamespaceCalls", num(100 * sum(calls[c] for c in namespace) / total_calls, 0))
    m.add("RevProfWriteTime", num(100 * seconds["write"] / total_s, 0))
    stored = max(1, calls["lsetxattr"])     # MinIO writes one xattr per stored S3 object
    directory = ("mkdirat", "openat", "renameat", "unlinkat", "faccessat")
    m.add("RevProfSyncTime", num(100 * sync_seconds / total_s, 1))
    m.add("RevProfSyncPerObject", f"{sync / stored:.2f}")
    m.add("RevProfDirectoryPerObject", num(sum(calls[c] for c in directory) / stored, 0))
    m.add("RevProfStraceCycles", len(list(strace_dir.glob("*-strace.txt"))))

    # Data disk under load (iostat extended statistics, one line per second).
    await_ms, util, depth, written = [], [], [], []
    for path in sorted(perf_dir.glob("*-iostat.txt")):
        header = None
        for line in path.read_text().splitlines():
            parts = line.split()
            if parts[:1] == ["Device"]:
                header = parts
            elif header and parts and parts[0] == "nvme1n1":
                row = dict(zip(header, parts))
                if float(row["w/s"]) > 1000:        # seconds with benchmark load only
                    await_ms.append(float(row["w_await"]))
                    util.append(float(row["%util"]))
                    depth.append(float(row["aqu-sz"]))
                    written.append(float(row["wkB/s"]) / 1024)
    m.add("RevProfDiskAwait", f"{statistics.median(await_ms):.2f}")
    m.add("RevProfDiskAwaitPninetyfive", f"{float(np.percentile(await_ms, 95)):.2f}")
    m.add("RevProfDiskUtil", num(statistics.median(util), 0))
    m.add("RevProfDiskQueue", f"{statistics.median(depth):.1f}")
    m.add("RevProfDiskSeconds", num(len(await_ms)))
    m.add("RevProfDiskWriteMib", num(statistics.median(written), 0))

    # CPU samples of the MinIO process: user code against kernel, and kernel lock spinning.
    user, kernel, locks = [], [], []
    lock_symbols = ("osq_lock", "rwsem_spin_on_owner", "mutex_spin_on_owner",
                    "native_queued_spin_lock_slowpath", "_raw_spin_lock", "rwsem_optimistic_spin",
                    "queued_spin_lock_slowpath", "_raw_spin_unlock_irqrestore")
    for path in sorted(perf_dir.glob("*-perf-dso.txt")):
        shares = {parts[1]: float(parts[0].rstrip("%")) for parts in
                  (line.split() for line in path.read_text().splitlines())
                  if len(parts) >= 2 and parts[0].endswith("%")}
        if not shares or shares.get("minio", 0) + shares.get("[kernel.kallsyms]", 0) < 50:
            continue
        self_text = (path.parent / path.name.replace("dso", "self")).read_text().splitlines()
        lock = sum(float(parts[0].rstrip("%")) for parts in (line.split() for line in self_text)
                   if len(parts) >= 4 and parts[0].endswith("%") and parts[3] in lock_symbols)
        user.append(shares.get("minio", 0.0))
        kernel.append(shares.get("[kernel.kallsyms]", 0.0))
        locks.append(lock)
    m.add("RevProfCpuUser", num(statistics.median(user), 0))
    m.add("RevProfCpuKernel", num(statistics.median(kernel), 0))
    m.add("RevProfCpuKernelLocks", num(statistics.median(locks), 0))
    m.add("RevProfPerfCycles", len(user))


