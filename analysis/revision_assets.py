def mmc_response(rate: float, s0: float, mu: float) -> float:
    servers = max(1, round(mu * s0))
    load = rate * s0
    if load >= servers:
        return float("inf")
    return s0 + fa.erlang_c(servers, load) * s0 / (servers - load)


def fit_load_dependent(train: list[tuple[float, float]], s0: float, mu: float):
    """W = S0 (1 + a rho^b / (1 - rho)), rho = rate / mu: least squares on log W over a grid."""
    best = None
    for a in np.geomspace(0.001, 2.0, 120):
        for b in np.linspace(1.0, 30.0, 117):
            err = sum((math.log(s0 * (1 + a * (r / mu) ** b / (1 - r / mu))) - math.log(w)) ** 2
                      for r, w in train)
            if best is None or err < best[0]:
                best = (err, a, b)
    return best[1], best[2]


def knee_rate(predict, low: float, high: float, limit: float) -> float:
    """Smallest rate at which the predicted mean response time exceeds `limit` (bisection)."""
    if predict(high) <= limit:
        return float("nan")
    for _ in range(60):
        mid = (low + high) / 2
        if predict(mid) > limit:
            high = mid
        else:
            low = mid
    return high


def queueing(tx: dict, out: Path, results: Path, m: Macros) -> list[dict]:
    records, table_rows = [], []
    fig, axes = plt.subplots(1, 2, figsize=(3.5, 2.25), sharey=True)
    for ax, size, tag in zip(axes, (1024, 65536), ("Small", "Mid")):
        closed = {c["concurrency"]: c["ops_per_s"] for c in tx.values()
                  if c["experiment"] == "final-h" and c["loop"] == "closed" and c["size"] == size}
        series = sorted((c for c in tx.values() if c["experiment"] == "final-h"
                         and c["loop"] == "open" and c["size"] == size), key=lambda c: c["rate"])
        for i, c in enumerate(series):
            c["train"] = i % 2 == 0
            c["stable"] = all(r["ops_per_s"] >= 0.97 * r["rate"] and r["wait_mean_ms"] < 10
                              for r in c["runs"])
        train = [c for c in series if c["train"]]
        s0 = train[0]["mean_ms"] / 1000
        mu_train = statistics.fmean(c["ops_per_s"] for c in train[-2:])
        mu_n = stats.interpolate_rate(closed)
        peak = max(closed.values())
        a, b = fit_load_dependent([(c["rate"], c["sojourn_mean_ms"] / 1000)
                                   for c in train if c["stable"]], s0, mu_train)
        models = {
            "mmc": lambda r: mmc_response(r, s0, mu_train),
            "state": lambda r: stats.state_dependent_response(r, mu_n),
            "load": lambda r: (s0 * (1 + a * (r / mu_train) ** b / (1 - r / mu_train))
                               if r < mu_train else float("inf")),
        }
        base = series[0]["sojourn_mean_ms"] / 1000
        errors = defaultdict(list)
        for c in series:
            row = {"size": size, "rate": c["rate"], "set": "train" if c["train"] else "held-out",
                   "stable": c["stable"], "achieved": c["ops_per_s"],
                   "measured_ms": c["sojourn_mean_ms"], "measured_lo": c["sojourn_mean_ms_lo"],
                   "measured_hi": c["sojourn_mean_ms_hi"], "service_ms": c["mean_ms"]}
            for name, predict in models.items():
                row[f"{name}_ms"] = predict(c["rate"]) * 1000
                if c["stable"] and not c["train"]:
                    errors[name].append(abs(row[f"{name}_ms"] / c["sojourn_mean_ms"] - 1))
            records.append(row)
        stable = [c for c in series if c["stable"]]
        last_stable = max(c["rate"] for c in stable)
        first_unstable = min(c["rate"] for c in series if not c["stable"])
        observed = min(c["rate"] for c in series if c["sojourn_mean_ms"] / 1000 > 2 * base)
        below = max(c["rate"] for c in series if c["rate"] < observed)
        knees = {name: knee_rate(predict, series[0]["rate"], 6000.0, 2 * base)
                 for name, predict in models.items()}
        overload = statistics.fmean(c["ops_per_s"] for c in series if not c["stable"])
        m.add(f"RevQ{tag}Peak", num(peak, -1))
        m.add(f"RevQ{tag}Overload", num(overload, -1))
        m.add(f"RevQ{tag}LastStable", num(last_stable))
        m.add(f"RevQ{tag}FirstUnstable", num(first_unstable))
        m.add(f"RevQ{tag}RhoLastStable", f"{last_stable / peak:.2f}")
        m.add(f"RevQ{tag}RhoFirstUnstable", f"{first_unstable / peak:.2f}")
        m.add(f"RevQ{tag}KneeLo", num(below))
        m.add(f"RevQ{tag}KneeHi", num(observed))
        m.add(f"RevQ{tag}HeldOut", len(errors["mmc"]))
        label = {"mmc": "Mmc", "state": "State", "load": "Load"}
        for name in models:
            m.add(f"RevQ{tag}Mape{label[name]}", num(100 * statistics.fmean(errors[name]), 0))
            m.add(f"RevQ{tag}Knee{label[name]}", num(knees[name], -1))
        m.add(f"RevQ{tag}ServiceLight", f"{series[0]['mean_ms']:.1f}")
        m.add(f"RevQ{tag}ServiceOverload",
              num(statistics.fmean(c["mean_ms"] for c in series if not c["stable"]), 0))
        table_rows.append([size_label(size), num(peak, -1), f"{num(last_stable)}/{num(first_unstable)}",
                           f"{num(below)}--{num(observed)}"]
                          + [f"{100 * statistics.fmean(errors[n]):.0f}\\%" for n in models]
                          + [num(knees[n], -1) for n in models])

        grid = np.linspace(series[0]["rate"], 5600, 400)
        for name, style, text in (("mmc", ":", "M/M/$c$"), ("state", "-", "state-dependent"),
                                  ("load", "--", "load-dependent fit")):
            ys = [models[name](r) * 1000 for r in grid]
            ax.plot(grid, [y if math.isfinite(y) else np.nan for y in ys], linestyle=style,
                    color=INK2 if name == "mmc" else COLOR["B1"] if name == "state" else COLOR["R1"],
                    linewidth=1.0, label=text)
        for flag, face, text in ((True, COLOR["P1"], "measured (training)"),
                                 (False, "white", "measured (held out)")):
            pts = [c for c in series if c["train"] == flag and c["stable"]]
            ax.plot([c["rate"] for c in pts], [c["sojourn_mean_ms"] for c in pts], linestyle="none",
                    marker="o", color=COLOR["P1"], markerfacecolor=face, label=text)
        pts = [c for c in series if not c["stable"]]
        ax.plot([c["rate"] for c in pts], [c["sojourn_mean_ms"] for c in pts], linestyle="none",
                marker="x", color=COLOR["P3"], label="unstable (lower bound)")
        ax.set_yscale("log")
        ax.set_ylim(3, 8000)
        ax.set_title(f"{size_label(size).replace(chr(92) + ',', ' ')} PUT, ML-KEM-768", fontsize=7.5)
        ax.set_xlabel("offered load (requests/s)")
    axes[0].set_ylabel("mean response time (ms)")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.tight_layout()
    fig.legend(handles, labels, fontsize=5.5, loc="upper center", ncol=3, bbox_to_anchor=(0.5, 0.0))
    fig.savefig(out / "fig-queue-rev.pdf")
    plt.close(fig)
    fa.write_csv(results / "queueing.csv", records)
    tex_table(out / "tab-queue.tex",
              ["Size", "Peak", "Stable/unstable", "Observed knee", "M/M/$c$", "State", "Load",
               "M/M/$c$", "State", "Load"], table_rows, "lrcc|ccc|ccc",
              " & & & & \\multicolumn{3}{c|}{Held-out error (MAPE)} & "
              "\\multicolumn{3}{c}{Predicted knee (req/s)}")
    return records


